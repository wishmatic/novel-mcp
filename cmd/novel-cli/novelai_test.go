func TestNovelAIWritesTheRequestedFormat(t *testing.T) {
	server, _ := captureServer(t, http.StatusOK, finalFrame(t, pngImage(t, 64, 64)))
	dir := t.TempDir()

	if _, _, err := runCommand(t, testDeps(t, server.URL),
		"novelai", "a cat", "--model", "m", "--format", "webp", "--out", dir,
	); err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	files, err := filepath.Glob(filepath.Join(dir, "novel-image-*.webp"))
	if err != nil {
		t.Fatalf("Glob() error: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("files = %v, want one webp image", files)
	}

	data, err := os.ReadFile(files[0])
	if err != nil {
		t.Fatalf("ReadFile() error: %v", err)
	}
	if !bytes.HasPrefix(data, []byte("RIFF")) || len(data) < 12 || string(data[8:12]) != "WEBP" {
		t.Error("the written file is not a WebP image")
	}
}
