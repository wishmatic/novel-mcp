func TestNovelAIWritesTheGeneratedImage(t *testing.T) {
	image := pngImage(t, 64, 64)
	server, requests := captureServer(t, http.StatusOK, finalFrame(t, image))
	dir := t.TempDir()

	out, _, err := runCommand(t, testDeps(t, server.URL),
		"novelai", "a", "cat",
		"--model", "nai-diffusion-5-full",
		"--negative-prompt", "bad",
		"--sampler-name", "k_dpmpp_2m",
		"--steps", "30",
		"--width", "832",
		"--height", "1216",
		"--cfg-scale", "5",
		"--seed", "42",
		"--format", "png",
		"--out", dir,
	)
	if err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	request := nextRequest(t, requests)
	if request.Path != "/ai/generate-image-stream" {
		t.Errorf("path = %s, want /ai/generate-image-stream", request.Path)
	}
	if request.Authorization != "Bearer test-key" {
		t.Errorf("Authorization = %q, want Bearer test-key", request.Authorization)
	}
	if request.ContentType != "application/json" {
		t.Errorf("Content-Type = %q, want application/json", request.ContentType)
	}

	body := request.jsonBody(t)
	if body["action"] != "generate" {
		t.Errorf("action = %v, want generate", body["action"])
	}
	if body["model"] != "nai-diffusion-5-full" {
		t.Errorf("model = %v, want nai-diffusion-5-full", body["model"])
	}
	if body["input"] != "a cat" {
		t.Errorf("input = %v, want a cat", body["input"])
	}

	params := paramsOf(t, body)
	if params["stream"] != "msgpack" {
		t.Errorf("stream = %v, want msgpack", params["stream"])
	}
	if params["sampler"] != "k_dpmpp_2m" {
		t.Errorf("sampler = %v, want k_dpmpp_2m", params["sampler"])
	}
	if params["negative_prompt"] != "bad" {
		t.Errorf("negative_prompt = %v, want bad", params["negative_prompt"])
	}

	checks := map[string]float64{
		"width":  832,
		"height": 1216,
		"steps":  30,
		"scale":  5,
		"seed":   42,
	}
	for field, want := range checks {
		if got := numberField(t, params, field); got != want {
			t.Errorf("%s = %v, want %v", field, got, want)
		}
	}

	files, err := filepath.Glob(filepath.Join(dir, "novel-image-*.png"))
	if err != nil {
		t.Fatalf("Glob() error: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("files = %v, want one image", files)
	}

	data, err := os.ReadFile(files[0])
	if err != nil {
		t.Fatalf("ReadFile() error: %v", err)
	}
	if !bytes.Equal(data, image) {
		t.Error("the written image does not match the generated bytes")
	}

	if !strings.Contains(out, dir) {
		t.Errorf("stdout = %q, want the written path", out)
	}
}

func TestNovelAIDefaultsMatchTheTool(t *testing.T) {
	server, requests := captureServer(t, http.StatusOK, finalFrame(t, pngImage(t, 64, 64)))
	dir := t.TempDir()

	if _, _, err := runCommand(t, testDeps(t, server.URL),
		"novelai", "a cat", "--out", dir,
	); err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	params := paramsOf(t, nextRequest(t, requests).jsonBody(t))

	checks := map[string]float64{
		"steps":  20,
		"scale":  7,
		"width":  512,
		"height": 512,
	}
	for field, want := range checks {
		if got := numberField(t, params, field); got != want {
			t.Errorf("%s = %v, want the tool's %v default", field, got, want)
		}
	}

	if params["sampler"] != novelai.DefaultSampler {
		t.Errorf("sampler = %v, want %s", params["sampler"], novelai.DefaultSampler)
	}
	if params["negative_prompt"] == "" {
		t.Error("negative_prompt is empty, want the tool's default")
	}
	if seed := numberField(t, params, "seed"); seed < 0 {
		t.Errorf("seed = %v, want a resolved random seed", seed)
	}

	files, err := filepath.Glob(filepath.Join(dir, "novel-image-*.webp"))
	if err != nil {
		t.Fatalf("Glob() error: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("files = %v, want one default webp image", files)
	}
}

func TestNovelAIRunsImg2ImgWithAnInitImage(t *testing.T) {
	initImage := pngImage(t, 320, 640)

	input := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		_, _ = w.Write(initImage)
	}))
	defer input.Close()

	server, requests := captureServer(t, http.StatusOK, finalFrame(t, pngImage(t, 64, 64)))
	dir := t.TempDir()

	if _, _, err := runCommand(t, testDeps(t, server.URL),
		"novelai", "a cat",
		"--model", "nai-diffusion-5-full",
		"--init-image-url", input.URL+"/image.png",
		"--out", dir,
	); err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	body := nextRequest(t, requests).jsonBody(t)
	if body["action"] != "img2img" {
		t.Errorf("action = %v, want img2img", body["action"])
	}

	params := paramsOf(t, body)
	if got := numberField(t, params, "strength"); got != 0.75 {
		t.Errorf("strength = %v, want the 0.75 default", got)
	}
	if got := numberField(t, params, "noise"); got != 0 {
		t.Errorf("noise = %v, want 0", got)
	}
	if got := numberField(t, params, "width"); got != 320 {
		t.Errorf("width = %v, want the init image's 320", got)
	}
	if got := numberField(t, params, "height"); got != 640 {
		t.Errorf("height = %v, want the init image's 640", got)
	}

	wantImage := base64.StdEncoding.EncodeToString(initImage)
	if params["image"] != wantImage {
		t.Errorf("image = %v, want the init image's raw base64", params["image"])
	}
}

